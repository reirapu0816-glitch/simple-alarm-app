CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)

def thin_border():
    s = Side(style="thin", color="AAAAAA")
    return Border(left=s, right=s, top=s, bottom=s)

def thick_top_border():
    thick = Side(style="medium", color="2F4F8F")
    thin  = Side(style="thin",   color="AAAAAA")
    return Border(left=thin, right=thin, top=thick, bottom=thin)

def header_row(ws, row, texts, fills, widths=None):
    for ci, (text, fill) in enumerate(zip(texts, fills), 1):
        c = ws.cell(row=row, column=ci, value=text)
        c.fill = fill
        c.font = WHITE if fill == HEADER_FILL else BOLD
        c.alignment = CENTER
        c.border = thin_border()
    if widths:
        for ci, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(ci)].width = w

def data_row(ws, row, texts, fill, font=None):
    for ci, text in enumerate(texts, 1):
        c = ws.cell(row=row, column=ci, value=text)
        c.fill = fill
        c.font = font or NORM
        c.alignment = WRAP
        c.border = thin_border()

def stage_header(ws, row, stage_label, fill, col_span_end, col=1):
    c = ws.cell(row=row, column=col, value=stage_label)
    c.fill = fill
    c.font = STAGE_FONT
    c.alignment = CENTER
    c.border = thick_top_border()
    ws.merge_cells(start_row=row, start_column=col,
                   end_row=row, end_column=col_span_end)

def set_col_widths(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

def set_row_height(ws, row, height):
    ws.row_dimensions[row].height = height


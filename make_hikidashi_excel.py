def make_type_sheet(wb, type_info):
    ws = wb.create_sheet(type_info["name"])
    ws.sheet_view.showGridLines = False
    set_col_widths(ws, [3, 28, 42, 36, 2])

    r = 1
    # タイトル
    c = ws.cell(r, 2, type_info["name"] + "　タイプ引き出し集")
    c.font = TITLE_FONT
    c.alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[r].height = 30
    r += 1

    c = ws.cell(r, 2, type_info["subtitle"])
    c.font = Font(bold=True, name="Arial", size=11, color="444444")
    c.alignment = WRAP
    ws.row_dimensions[r].height = 20
    r += 1

    # プロフィール
    c = ws.cell(r, 2, "【このタイプの特徴】")
    c.fill = SECTION_FILL; c.font = BOLD; c.alignment = WRAP
    c.border = thin_border()
    ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=4)
    ws.row_dimensions[r].height = 18
    r += 1

    c = ws.cell(r, 2, type_info["profile"])
    c.fill = ACCENT_FILL; c.font = NORM; c.alignment = WRAP
    c.border = thin_border()
    ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=4)
    ws.row_dimensions[r].height = 40
    r += 2

    # 各ステージ
    for stage in type_info["stages"]:
        stage_header(ws, r, stage["label"], stage["fill"], 4, col=2)
        ws.row_dimensions[r].height = 22
        r += 1

        # カラムヘッダー
        header_row(ws, r,
            ["引き出し", "具体的なアプローチ・やり方", "使えるフレーズ例"],
            [HEADER_FILL, HEADER_FILL, HEADER_FILL])
        ws.row_dimensions[r].height = 18
        r += 1

